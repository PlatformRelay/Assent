}

# TEST-03 was "the floor sits at exactly 90.0% — steering, not measuring". The
# MEASURED number is read out of the transcript, never the "(required: NN%)"
# text, so this check is indifferent to how the floor is spelled.
check_coverage_bar() { # <transcript>
  local tr="$1"
  [[ -f "$tr" ]] || {
    echo "  TEST-03: missing 'task check' transcript $tr" >&2
    return 1
  }
  local plain="$WORK/cov.plain"
  strip_ansi "$tr" >"$plain"

  # Anchored at column 1 AND on a digit right after the colon-space: `go test
  # -coverprofile` prints a per-PACKAGE `…  coverage: 92.3% of statements` on
  # every ok line (not at column 1, already excluded by the anchor), and
  # EX-S08's dogfood-examples stage echoes ONE "coverage: OK — N rule(s),
  # every rule tested in both polarities" line per example pack (at column 1,
  # excluded only by the digit check — "OK" is not `[0-9]`). Grading on either
  # impostor would either compare the worst package against the aggregate bar
  # or count N-pack lines as N spurious "aggregate" measurements. Only the
  # gate's own `echo "coverage: ${pct}% (required: …)"` (Taskfile.yml
  # coverage:) starts the line with a digit.
  local hits="$WORK/hits.coverage"
  awk '/^coverage: [0-9]/ { print }' "$plain" >"$hits"
  local n
  n="$(wc -l <"$hits" | tr -d '[:space:]')"
  if ((n != 1)); then
    echo "  TEST-03: expected exactly ONE line starting 'coverage: NN.N%' in the 'task check' transcript (the D-010 gate's own echo); found $n — the coverage stage printed nothing this gate can grade, so the ${COVERAGE_BAR}% bar would be asserted vacuously" >&2
    return 1
  fi

  local pct
  pct="$(sed -e 's/^coverage: //' -e 's/%.*$//' "$hits")"
  if [[ ! "$pct" =~ ^[0-9]+\.[0-9]+$ ]]; then
    echo "  TEST-03: could not parse a percentage out of the coverage line '$(cat "$hits")'" >&2
    return 1
  fi
  awk -v p="$pct" -v bar="$COVERAGE_BAR" 'BEGIN { exit (p + 0 >= bar + 0 ? 0 : 1) }' || {
    echo "  TEST-03: measured aggregate internal/ coverage is ${pct}%, below the AUD-S13 bar of ${COVERAGE_BAR}% — the D-010 gate is back to steering rather than measuring" >&2
    return 1
  }
  echo "     measured coverage: ${pct}% (bar ${COVERAGE_BAR}%)"
  return 0
}

