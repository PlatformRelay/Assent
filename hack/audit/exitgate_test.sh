  local n
  n="$(wc -l <"$banners" | tr -d '[:space:]')"
  if ((n < 10)); then
    echo "  AUD-S18: only $n 'task: [stage]' banner(s) in the transcript; ${#CHECK_STAGES[@]} stages are pinned — the banner extraction broke (colour codes? --silent?), so the stage assertions below would be vacuous" >&2
