# ABSENCE assertions over a fixed corpus. Both halves of the vacuity risk are
# controlled: the corpus is required to be present and non-trivial (a moved or
# renamed file would otherwise silently shrink the search), and every phrase has
# a mutation control that re-injects it and requires the right finding ID.
check_retired_phrases() { # <root>
  local root="$1" rc=0

  local present=()
  local f
  for f in "${PHRASE_CORPUS[@]}"; do
    [[ -f "$root/$f" ]] && present+=("$f")
  done
  if ((${#present[@]} < PHRASE_CORPUS_MIN)); then
    echo "  DOC-08: only ${#present[@]} of ${#PHRASE_CORPUS[@]} front-of-house surfaces exist under $root (minimum $PHRASE_CORPUS_MIN) — the corpus shrank, so every 'phrase absent' assertion below would be vacuous" >&2
    return 1
  fi
  for f in README.md API_STABILITY.md docs/usage/walkthrough.md cmd/assent/main.go; do
    [[ -f "$root/$f" ]] || {
      echo "  DOC-08: required front-of-house surface $f is missing from the corpus root $root — the pins that cover it cannot fire" >&2
      rc=1
    }
  done
  ((rc == 0)) || return "$rc"

  # Positive control on the SEARCH ITSELF: a token that must be found in every
  # corpus file. If this comes up empty the matcher is broken, not the tree.
  local canary_missing=()
  for f in "${present[@]}"; do
    grep -Fq -- 'assent' "$root/$f" || canary_missing+=("$f")
  done
  if ((${#canary_missing[@]} > 0)); then
    echo "  DOC-08: the canary token is absent from ${canary_missing[*]} — the phrase matcher is not actually reading these files, so 'no retired phrase found' means nothing" >&2
    return 1
  fi

  # phrase|finding-id|scope (scope empty = whole corpus)
  local rules=(
    'no commands implemented yet|DOC-08|'
    'pre-alpha|DOC-08|'
    'design fiction|DOC-09|'
    'Nothing below is implemented|DOC-09|'
    'assent lint .assent/|DOC-07|'
    '0014-policy-test-harness|DOC-05|'
    'not yet implemented|DOC-06|API_STABILITY.md docs/api-stability.md'
  )
  local rule phrase finding scope files hits
  for rule in "${rules[@]}"; do
    phrase="${rule%%|*}"
    finding="${rule#*|}"
    finding="${finding%%|*}"
    scope="${rule##*|}"
    if [[ -n "$scope" ]]; then
      files=()
      for f in $scope; do [[ -f "$root/$f" ]] && files+=("$f"); done
      if ((${#files[@]} == 0)); then
        echo "  $finding: the scoped corpus for '$phrase' is empty under $root — the pin would be vacuous" >&2
        rc=1
        continue
      fi
    else
      files=("${present[@]}")
    fi
    hits="$WORK/hits.phrase"
    : >"$hits"
    for f in "${files[@]}"; do
      grep -Fin -- "$phrase" "$root/$f" | sed "s|^|$f:|" >>"$hits" || true
    done
    if [[ -s "$hits" ]]; then
      echo "  $finding: the retired pre-release phrase '$phrase' is back on a front-of-house surface:" >&2
      sed 's/^/    /' "$hits" >&2
      rc=1
    fi
  done
  return "$rc"
}

