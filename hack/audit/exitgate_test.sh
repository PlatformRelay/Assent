# go-task colours its stage banners even when stdout is a file, and BSD/GNU sed
# disagree about \x1b. Build ESC with sprintf so the awk program stays portable.
strip_ansi() { # <file>
  awk 'BEGIN { ESC = sprintf("%c", 27) } { gsub(ESC "\\[[0-9;]*m", "", $0); print }' "$1"
}

# Emits `<lineno>:<line>` for every line whose first non-blank character is not
# `#`. Presence assertions must never read raw lines (review finding F1: a
# commented-out flag satisfied a naive grep and the gate reported OK).
code_view() { # <file>
  awk '{
    s = $0
    sub(/^[[:space:]]+/, "", s)
    if (substr(s, 1, 1) != "#") printf "%d:%s\n", FNR, $0
  }' "$1"
}

# Emits `<lineno>:<command>`: whole-line comments dropped, inline comment tail
# removed, list dash and `run:` key stripped. Anchoring a presence check on this
# makes `run: echo skipped  # was: bash …` structurally unable to satisfy it
# (review finding N1).
command_view() { # <file>
  awk '{
    s = $0
    sub(/^[[:space:]]+/, "", s)
    if (substr(s, 1, 1) == "#") next
    sub(/[[:space:]]#.*$/, "", s)
    sub(/^-[[:space:]]+/, "", s)
    sub(/^run:[[:space:]]*/, "", s)
    sub(/[[:space:]]+$/, "", s)
    printf "%d:%s\n", FNR, s
  }' "$1"
}

# Emits one Taskfile task's block, comment-stripped and left-trimmed: from the
# `  <name>:` key to the next key at the same indent. Same extraction shape as
# check_check_wiring's inline awk over `check:`, generalised so stage BODIES can
# be pinned by content and not only by name.
task_body() { # <taskfile> <task-name>
  awk -v want="  $2:" '
    index($0, want) == 1 && length($0) == length(want) { inblock = 1; next }
    inblock && /^  [a-zA-Z0-9_:.-]+:$/ { inblock = 0 }
    inblock {
      s = $0
      sub(/^[[:space:]]+/, "", s)
      if (substr(s, 1, 1) == "#") next
      print s
    }
  ' "$1"
}

# Isolate the YAML step containing <lineno>: walk BACK to the nearest step
# marker at <indent>, then forward to the next one. Review finding N5: an
# extraction that starts AT the `run:` line cannot see `if:` /
# `continue-on-error:` in their conventional position, ABOVE `run:`.
isolate_step() { # <file> <lineno> <step-marker-ere>
  awk -v target="$2" -v marker="$3" '
    { lines[NR] = $0 }
    $0 ~ marker { starts[NR] = 1 }
    END {
      start = 0
      for (i = target; i >= 1; i--) if (i in starts) { start = i; break }
      if (start == 0) exit 1
      end = NR
      for (i = start + 1; i <= NR; i++) if (i in starts) { end = i - 1; break }
      for (i = start; i <= end; i++) print lines[i]
    }
  ' "$1"
}

# True when the isolated step carries an `if:` or `continue-on-error:` — present
# but DISARMED, the most realistic "just unblock CI" edit, and one actionlint
# stays green on.
step_disarmed() { # <step-file> <out-file>
  grep -En '^[[:space:]]*(continue-on-error|if):' "$1" >"$2" || true
  [[ -s "$2" ]]
}

# Number of REAL `run:` keys in an isolated step (whole-line comments dropped).
# Exactly one is the only sane answer. Two means the isolation swallowed the
# NEIGHBOURING step — which is precisely what deleting a step's `- name:` line
# does, and it is the disarm `workflow_pins_test.sh` carries a control for. A
# merged region still "contains the invocation" and still "starts with a step
# marker", so without this the `env:`/`if:`/`continue-on-error:` assertions
# would be reading a region that is not one step.
step_run_count() { # <step-file>
  awk '{
    s = $0
    sub(/^[[:space:]]+/, "", s)
    if (substr(s, 1, 1) == "#") next
    if (s ~ /^run:/) n++
  } END { printf "%d\n", n + 0 }' "$1"
}

# `cmd | head -1` closes the read end early: under `set -o pipefail` the writer
# takes SIGPIPE and the pipeline exits 141. This file bans that shape (it is one
# of the repo's recurring "test that cannot fail" defects), so first lines come
# from a file, never from a pipe.
first_line() { # <file>
  awk 'NR == 1 { print; exit }' "$1"
}

joined_run_re() { # <name>...
  local out="" n
  for n in "$@"; do out="${out:+$out|}$n"; done
  printf '%s\n' "$out"
}

# `grep -F` cannot anchor. This does: fixed string, must start at column 1.
has_prefix_line() { # <file> <fixed prefix>
  awk -v want="$2" 'index($0, want) == 1 { found = 1 } END { exit !found }' "$1"
}

count_prefix_lines() { # <file> <fixed prefix>
  awk -v want="$2" 'index($0, want) == 1 { n++ } END { printf "%d\n", n + 0 }' "$1"
}

# --------------------------------------------------------- mutation harness --

mutate() { # <file> <sed-program> <string that must appear afterwards>
  local file="$1" program="$2" witness="$3"
  local before after
  before="$(cat "$file")"
  sed "$program" "$file" >"$file.mut"
  mv "$file.mut" "$file"
  after="$(cat "$file")"
  [[ "$before" != "$after" ]] ||
    fail "mutation harness: sed program '$program' did not change $file — the mutant is identical to the clean input, so any 'the check fires' conclusion is false"
  grep -Fq -- "$witness" "$file" ||
    fail "mutation harness: expected '$witness' in $file after mutation, but it is absent"
}

mutate_awk() { # <file> <awk-program> <string that must appear afterwards>
  local file="$1" program="$2" witness="$3"
  local before after
  before="$(cat "$file")"
  awk "$program" "$file" >"$file.mut"
  mv "$file.mut" "$file"
  after="$(cat "$file")"
  [[ "$before" != "$after" ]] ||
    fail "mutation harness: awk program did not change $file — the mutant is identical to the clean input, so any 'the check fires' conclusion is false"
  grep -Fq -- "$witness" "$file" ||
    fail "mutation harness: expected '$witness' in $file after mutation, but it is absent"
}

expect_green() { # <check-fn> <label> <args...>
  local fn="$1" label="$2"
  shift 2
  "$fn" "$@" || fail "$label — the real input violates $fn (see the findings above)"
  echo "OK: $label"
}

# A control that reds is not yet a control that WORKS: it could be red for an
# unrelated reason, which would mask the mutation going undetected. So every
# control pins the finding text it must produce.
expect_red() { # <check-fn> <label> <required stderr fragment> <args...>
  local fn="$1" label="$2" want="$3"
  shift 3
  local err="$WORK/expect_red.err"
  if "$fn" "$@" 2>"$err"; then
    fail "mutation control: $fn accepted an input that DOES carry the violation ($label) — this check cannot fail and is therefore not a gate"
  fi
  grep -Fq -- "$want" "$err" || {
    echo "  actual finding was:" >&2
    sed 's/^/    /' "$err" >&2
    fail "mutation control: $fn went red on '$label' but NOT for its stated reason — the finding was expected to mention: $want"
  }
  echo "OK: mutation control — $fn goes red on: $label"
}

copy_file() { # <src> <dst>  (creates parent dirs)
  mkdir -p "$(dirname "$2")"
  cp "$1" "$2"
}

