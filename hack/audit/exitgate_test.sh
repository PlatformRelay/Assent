# The one permitted difference, per D-120 / the spec Appendix A.2.
SCHEMA_PERMITTED_FILE='schemas/decision/v1alpha1/decision-record.schema.json'
SCHEMA_PERMITTED_REMOVED='"description": "Content digest of the evaluating tool build'
SCHEMA_PERMITTED_ADDED='"description": "Deterministic build-content proxy for the evaluating tool'

# Extension pin: narrowing (6) to *.json must not become a loophole through
# which a .yaml/.cue/.json5 schema lands outside the guard entirely.
#
# EXTENSION-LESS files are bucketed as the pseudo-extension `(none)` and are
# therefore REFUSED, because `(none)` is not in SCHEMA_EXTENSIONS. The first cut
# of this check listed `find … -name '*.*'`, which never sees a dotless name at
# all: a committed `schemas/FROZEN` passed here AND passed check_schema_freeze
# (whose `$NF ~ /\.json$/` filter drops it from --name-status), so the "cannot
# become a loophole" claim in D-132 and hack/audit/README.md was false for
# exactly one file shape. Closed here rather than by widening the freeze
# filter: that narrowing is deliberate, so AUD-S16's legitimate schemas/*.go
# edits do not red the freeze guard.
#
# The extension is taken from the BASENAME, not the path: a dot in a directory
# component (`schemas/v1.0/x`) would otherwise be read as the file's extension.
check_schema_extensions() { # <schemas-dir>
  local dir="$1"
  [[ -d "$dir" ]] || {
    echo "  ARCH-03: missing schemas directory $dir" >&2
    return 1
  }
  local exts="$WORK/schemas.exts"
  find "$dir" -type f |
    awk '{
      n = $0
      sub(/.*\//, "", n)
      if (n ~ /\./) { sub(/.*\./, "", n); print n } else { print "(none)" }
    }' | sort -u >"$exts"
  if [[ ! -s "$exts" ]]; then
    echo "  ARCH-03: no files found under $dir — the extension pin would be vacuous" >&2
    return 1
  fi
  local want
  want="$(printf '%s\n' $SCHEMA_EXTENSIONS | sort -u)"
  local got
  got="$(cat "$exts")"
  if [[ "$want" != "$got" ]]; then
    echo "  ARCH-03: the extension set under $dir is [$(echo $got)], pinned is [$(echo $want)] — the freeze guard is scoped to *.json, so a schema in another format would sit entirely outside it ('(none)' means an extension-less file, which the freeze guard's \$NF ~ /\\.json\$/ filter also drops) (D-132)" >&2
    return 1
  fi
  return 0
}

# Ref-relative, not working-tree-relative. A COMMITTED schema change is the only
# kind that ships, and `git diff schemas/` is silent on those.
check_schema_freeze() { # <repo-dir> <base-ref> <min-json-at-base>
  local dir="$1" base="$2" minjson="$3" rc=0

  command -v git >/dev/null 2>&1 || {
    echo "  ARCH-03: git is not available — the ref-relative schema freeze cannot be evaluated" >&2
    return 1
  }

  # The base is overridable (ASSENT_AUDIT_SCHEMA_BASE) so the guard can be moved
  # FORWARD to a later released tag. Nothing else: `HEAD`, a branch or a raw SHA
  # would make the diff trivially empty and this check vacuous, which is exactly
  # the disarm shape the rest of this file exists to refuse. Note that
  # "base resolves to HEAD" is NOT the discriminator — right after a tag that is
  # legitimate — so the constraint is on the SHAPE of the ref: a release tag.
  if [[ ! "$base" =~ ^v[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "  ARCH-03: schema-freeze base '$base' is not a release tag of the form vX.Y.Z — the baseline must be an IMMUTABLE ref, or the freeze check compares the tree against itself and passes over any schema change (D-132)" >&2
    return 1
  fi
  git -C "$dir" rev-parse --verify --quiet "refs/tags/${base}" >/dev/null || {
    echo "  ARCH-03: '$base' is not a tag in $dir — the baseline must be the released tag itself, not a same-named branch or a loose revision" >&2
    return 1
  }
  git -C "$dir" rev-parse --verify --quiet "${base}^{commit}" >/dev/null || {
    echo "  ARCH-03: base ref '$base' does not resolve in $dir — the frozen-schema baseline is unreachable (a shallow checkout without tags will do this; the job needs fetch-depth: 0)" >&2
    return 1
  }

  # Positive control: the baseline must actually list the schema corpus. Without
  # it a pathspec that stopped matching would compare an empty set to an empty
  # set and report the schemas frozen.
  local baselist="$WORK/schemas.base"
  git -C "$dir" ls-tree -r --name-only "$base" -- schemas 2>/dev/null |
    grep -E '\.json$' >"$baselist" || true
  local n_base
  n_base="$(wc -l <"$baselist" | tr -d '[:space:]')"
  if ((n_base < minjson)); then
    echo "  ARCH-03: base ref '$base' lists only $n_base JSON file(s) under schemas/ (expected at least $minjson) — the pathspec is not matching, so 'schemas frozen' would be vacuous" >&2
    return 1
  fi

  local status="$WORK/schemas.status"
  git -C "$dir" diff --name-status "$base" -- schemas >"$status" 2>/dev/null || {
    echo "  ARCH-03: 'git diff --name-status $base -- schemas' failed in $dir" >&2
    return 1
  }

  local changed="$WORK/schemas.changed_json"
  awk -F'\t' '$NF ~ /\.json$/ { print }' "$status" >"$changed" || true

  # Additions and deletions are never permitted: the only sanctioned schema diff
  # in this epic is one description string.
  local addel="$WORK/schemas.addel"
  awk -F'\t' '$1 !~ /^M/ { print }' "$changed" >"$addel" || true
  if [[ -s "$addel" ]]; then
    echo "  ARCH-03: JSON schema file(s) added, deleted or renamed since $base — the frozen v1alpha1 contract set changed:" >&2
    sed 's/^/    /' "$addel" >&2
    rc=1
  fi

  local modified="$WORK/schemas.modified"
  awk -F'\t' '$1 ~ /^M/ { print $NF }' "$changed" >"$modified" || true

  local f
  while IFS= read -r f; do
    [[ -n "$f" ]] || continue
    if [[ "$f" != "$SCHEMA_PERMITTED_FILE" ]]; then
      echo "  ARCH-03: frozen schema $f changed since $base — no semantic change to any FROZEN schema is permitted in this epic (the only sanctioned diff is the D-120 toolDigest description in $SCHEMA_PERMITTED_FILE)" >&2
      git -C "$dir" diff "$base" -- "$f" >&2 || true
      rc=1
      continue
    fi
    # The permitted file: every changed line must belong to the D-120 edit.
    local hunk="$WORK/schemas.hunk"
    git -C "$dir" diff --unified=0 "$base" -- "$f" >"$hunk" 2>/dev/null || true
    local body="$WORK/schemas.hunk.body"
    grep -E '^[+-]' "$hunk" | grep -Ev '^(\+\+\+|---)' >"$body" || true
    local n_body
    n_body="$(wc -l <"$body" | tr -d '[:space:]')"
    if ((n_body != 2)); then
      echo "  ARCH-03: $f has $n_body changed line(s) since $base; exactly 2 are permitted (the D-120 toolDigest description replacement):" >&2
      sed 's/^/    /' "$body" >&2
      rc=1
      continue
    fi
    # Split by direction first: the diff marker and the payload are separated by
    # the JSON indentation, so a single fixed string spanning both would never
    # match (and a check that never matches is a check that always... reds here,
    # but the message would be wrong, which is its own failure mode).
    local minus="$WORK/schemas.hunk.minus" plus="$WORK/schemas.hunk.plus"
    awk 'substr($0, 1, 1) == "-" { print }' "$body" >"$minus"
    awk 'substr($0, 1, 1) == "+" { print }' "$body" >"$plus"
    local removed added
    removed="$(grep -c -F -- "$SCHEMA_PERMITTED_REMOVED" "$minus" || true)"
    added="$(grep -c -F -- "$SCHEMA_PERMITTED_ADDED" "$plus" || true)"
    if ((removed != 1)) || ((added != 1)); then
      echo "  ARCH-03/D-120: the two changed lines in $f are not the sanctioned toolDigest description replacement (removed-match=$removed added-match=$added):" >&2
      sed 's/^/    /' "$body" >&2
      rc=1
    fi
  done <"$modified"
  return "$rc"
}

