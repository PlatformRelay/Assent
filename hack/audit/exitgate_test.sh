#
# ONE invocation asserts seven things, and every failure names the audit finding
# ID it reopens:
#
#   (1) REL-07  — the AUD-S01 fail-closed cassettes PASS by name (not "go test
#                 exited 0", which a `-run` regex matching nothing also does).
#   (2) RELSE-01/TEST-03 — `task check` is green with all pinned stages
#                 actually executed (incl. `changelog-verify`) and the measured
#                 aggregate coverage at or above the epic's 91.0% bar.
#   (3) RELSE-05 — the release job still runs the verify-green-on-tag-SHA gate,
#                 before anything is built/signed/published, undisarmed.
#   (4) DOC-05..DOC-11 — the AUD-S05/S06 truth pins pass and no retired
#                 pre-release phrase has resurfaced on a front-of-house surface.
#   (5) determinism — the wired double-run gate is green AND each test named in
#                 its `-run` patterns really ran.
#   (6) ARCH-03/D-120 — the frozen JSON schemas are unchanged against an
#                 IMMUTABLE base ref, except the one permitted D-120 line.
#   (7) REQ-AUD-S18-02 — the finding→disposition table in
#                 openspec/specs/p5-aud-audit-remediation/spec.md covers every
#                 2026-08-06 finding ID, and every row resolves.
#
# WHAT THIS GATE DOES NOT CERTIFY. It is scoped to the 2026-08-06 audit. Two
# decision-path fail-opens found DURING this epic (OQ-27 relational CEL compare
# over string-bound operands, since CLOSED by D-131; OQ-28 `repo_file` symlink
# escape, since CLOSED — D-133 refuses checkout symlinks at enumeration and
# D-129 adds the provider-layer guard, both now on `main`)
# are not audit findings and blocked the tag independently of anything graded
# here. Check (7b) pins the spec's "Post-audit release blockers"
# section and requires each cited OQ to resolve and to carry a status token, so
# a green run here can never be read as release clearance. The gate does NOT
# grade the statuses themselves — it grades that the record exists and is
# readable. See D-132.
#
# ---------------------------------------------------------------------------
# WHY (6) IS NOT `git diff schemas/`
#
# The pre-existing freeze guard (hack/compare/exitgate_test.sh:14-19, PCS-S09 /
# D-118) diffs the WORKING TREE. That is silent on COMMITTED schema changes —
# which are the only kind that ship. "git diff schemas/ is clean at the exit
# gate" was true and meaningless. This gate diffs against an IMMUTABLE base ref
# (the released tag v0.1.0 by default), so a committed schema edit reds it and
# the baseline cannot be regenerated by the same commit that changes the schema.
# Scope narrows to `schemas/**/*.json` because `schemas/` also holds Go code that
# AUD-S16 legitimately changed; the extension set under `schemas/` is pinned so
# that narrowing cannot become a loophole. Recorded in D-132.
#
# ---------------------------------------------------------------------------
# ANTI-VACUITY DISCIPLINE (the standard set by hack/lint/workflow_pins_test.sh)
#
# This repo has shipped nine-plus "tests that cannot fail". This is the gate
# that is supposed to catch rot, so every check here obeys the same rules:
#
#   * Every check is a FUNCTION over an input path, never a straight-line
#     assertion. Each is run against the real input (must be GREEN) and against
#     an input carrying the very violation it exists to catch (must be RED, and
#     red FOR ITS OWN STATED REASON — expect_red pins a message fragment).
#   * Every ABSENCE assertion gets a positive control, and every EXTRACTION is
#     checked non-empty and at/above a known-present count, so a pattern that
#     silently stopped matching fails loudly instead of passing vacuously.
#   * `go test ... -run RE` exits 0 when RE matches nothing. Every test-driving
#     check therefore parses `-v` output for `--- PASS: <name>` BY NAME.
#   * Portable ERE only: no `\t`, `\s`, `\b`, no `grep -P`. GNU grep does not
#     honour `\t` in an ERE where BSD grep does, and in a negative assertion
#     that divergence passes OPEN on Linux while looking green on macOS.
#   * No `grep -q` on the read end of a pipe: under `set -o pipefail` the early
#     close raises SIGPIPE and the pipeline exits 141. Matches go to a file.
#   * Presence assertions read a COMMENT-STRIPPED view: `# run: <thing>` and
#     `run: echo skip  # was: <thing>` must not satisfy them (findings F1/N1 of
#     the workflow_pins_test.sh review, reproduced here rather than re-learned).
#
# MODES. Default: everything. `--text-only`: the pure-text layer plus the FULL
# mutation harness, for running under Linux/GNU grep + mawk in a bare container
# (`docker run --rm -v "$PWD:/w" -w /w debian:stable-slim bash hack/audit/exitgate_test.sh --text-only`).
# check_ci_wiring asserts CI invokes this script with NO arguments, so the flag
