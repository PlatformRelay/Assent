# The test names come from the Taskfile's own `-run` patterns, so this cannot
# drift from the gate it grades. Positive-controlled: an extraction that stopped
# matching would leave nothing to assert.
extract_determinism_tests() { # <taskfile> -> one name per line
  awk '
    /^  determinism:$/ { inblock = 1 }
    inblock && /^  [a-zA-Z0-9_:-]+:$/ && !/^  determinism:$/ { inblock = 0 }
    inblock { print }
  ' "$1" |
    grep -Eo -- "-run ('[^']+'|[A-Za-z0-9_|]+)" |
    sed -e "s/^-run //" -e "s/^'//" -e "s/'$//" |
    tr '|' '\n' |
    sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' |
    grep -E '^Test[A-Za-z0-9_]+$' |
    sort -u
}

check_determinism_transcript() { # <transcript> <names-file>
  local tr="$1" names="$2" rc=0
  [[ -f "$tr" ]] || {
    echo "  AUD-S18 determinism: missing transcript $tr" >&2
    return 1
  }
  [[ -s "$names" ]] || {
    echo "  AUD-S18 determinism: the Taskfile -run extraction produced NO test names — every assertion below would be vacuous" >&2
    return 1
  }
  local n_names
  n_names="$(wc -l <"$names" | tr -d '[:space:]')"
  if ((n_names < 8)); then
    echo "  AUD-S18 determinism: extracted only $n_names test name(s) from the Taskfile determinism task; at least 8 are expected — the extraction is under-counting" >&2
    return 1
  fi

  local n_pass
  n_pass="$(count_prefix_lines "$tr" '--- PASS: ')"
  if ((n_pass == 0)); then
    echo "  AUD-S18 determinism: the transcript contains ZERO '--- PASS:' lines — 'go test -count=2 -run RE' exits 0 when RE matches nothing, so this run proves nothing" >&2
    return 1
  fi
  local failures="$WORK/hits.det_failures"
  grep -E '^(--- FAIL:|FAIL[[:space:]])' "$tr" >"$failures" || true
  if [[ -s "$failures" ]]; then
    echo "  AUD-S18 determinism: the double-run determinism gate is RED:" >&2
    sed 's/^/    /' "$failures" >&2
    rc=1
  fi

  local t
  while IFS= read -r t; do
    [[ -n "$t" ]] || continue
    local seen
    seen="$(count_prefix_lines "$tr" "--- PASS: $t ")"
    if ((seen < 2)); then
      echo "  AUD-S18 determinism: $t passed $seen time(s) under -count=2, expected 2 — a double-run gate that ran once (or not at all) is not a determinism gate" >&2
      rc=1
    fi
  done <"$names"
  return "$rc"
}

