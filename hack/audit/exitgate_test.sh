# Parses `go test -v` output. Named-PASS, not exit code: `go test -run RE` exits
# 0 when RE matches nothing, so an exit-code check here would be exactly the
# "extraction that matched nothing and swept an empty set" defect.
check_s01_cassettes() { # <transcript>
  local tr="$1" rc=0
  [[ -f "$tr" ]] || {
    echo "  REL-07: missing go-test transcript $tr" >&2
    return 1
  }

  # Positive control on the transcript SHAPE. Without it, a transcript produced
  # by a `-run` pattern that matched nothing ("ok  pkg  0.01s [no tests to run]")
  # would satisfy every per-name assertion vacuously... by containing none of
  # them and reporting zero failures.
  local n_pass
  n_pass="$(count_prefix_lines "$tr" '--- PASS: ')"
  if ((n_pass == 0)); then
    echo "  REL-07: the go-test transcript contains ZERO '--- PASS:' lines — either the -run pattern matched no test (go test exits 0 for that) or -v was dropped; the per-cassette assertions below would be vacuous" >&2
    return 1
  fi

  local failures="$WORK/hits.s01_failures"
  grep -E '^(--- FAIL:|FAIL[[:space:]])' "$tr" >"$failures" || true
  if [[ -s "$failures" ]]; then
    echo "  REL-07: the AUD-S01 fail-closed cassettes are RED — the truncated/404 changed-file enumeration guard is not proven:" >&2
    sed 's/^/    /' "$failures" >&2
    rc=1
  fi

  local t
  for t in "${S01_TESTS_GITLAB[@]}" "${S01_TESTS_CMD[@]}"; do
    has_prefix_line "$tr" "--- PASS: $t " || {
      echo "  REL-07: cassette $t did not PASS (no '--- PASS: $t' in the transcript) — a renamed, deleted or skipped cassette leaves the D-042 self-vouch guard unproven against a truncated enumeration" >&2
      rc=1
    }
  done
  return "$rc"
}

