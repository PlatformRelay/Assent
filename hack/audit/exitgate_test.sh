check_release_verify_gate() { # <workflows-dir>
  local dir="$1" rc=0
  local wf="$dir/release.yaml"
  [[ -f "$wf" ]] || {
    echo "  RELSE-05: missing $wf" >&2
    return 1
  }

  local cmds="$WORK/cmd.release"
  command_view "$wf" >"$cmds"

  # Read as a COMMAND, anchored at its start: neither `# run: bash …` nor
  # `run: echo skip  # was: bash …` can satisfy this.
  local hits="$WORK/hits.release_gate"
  grep -E '^[0-9]+:bash[[:space:]]+hack/release/verify-tag-gate\.sh([[:space:]]|$)' "$cmds" >"$hits" || true
  if [[ ! -s "$hits" ]]; then
    echo "  RELSE-05: the release job does not RUN 'bash hack/release/verify-tag-gate.sh' as an actual command — a tag on a red commit would ship signed, attested artifacts again (v0.1.0 did)" >&2
    return 1
  fi

  local lineno
  lineno="$(awk -F: 'NR == 1 { print $1 }' "$hits")"
  local step="$WORK/step.release_gate"
  isolate_step "$wf" "$lineno" '^      - ' >"$step" || true

  # Positive controls on the isolation: a slab of file header would otherwise
  # satisfy a bare non-empty test (review finding N5).
  local n_step
  n_step="$(wc -l <"$step" | tr -d '[:space:]')"
  if [[ ! -s "$step" ]] || ((n_step > 10)); then
    echo "  RELSE-05: could not isolate the verify-green gate step in release.yaml (got $n_step lines, expected 1..10) — the extraction broke, so the disarm assertion below would be vacuous" >&2
    return 1
  fi
  grep -Eq '^      - ' "$step" || {
    echo "  RELSE-05: the isolated region does not START with a step marker — it is not a step, so the disarm assertion would be vacuous" >&2
    return 1
  }
  grep -Fq 'verify-tag-gate.sh' "$step" || {
    echo "  RELSE-05: the isolated step does not contain the gate invocation — the wrong step was isolated" >&2
    return 1
  }
  local n_run
  n_run="$(step_run_count "$step")"
  if ((n_run != 1)); then
    echo "  RELSE-05: the isolated region carries $n_run 'run:' key(s), not 1 — two steps were merged (deleting a step's '- name:' line does exactly that), so the disarm and ordering assertions below would be reading a region that is not one step" >&2
    return 1
  fi

  # Step-scoped, so the release job's legitimate JOB-level
  # `if: github.event_name == 'push' || …` is not mistaken for a disarm.
  local disabled="$WORK/hits.release_gate_disabled"
  if step_disarmed "$step" "$disabled"; then
    echo "  RELSE-05: the verify-green gate step is present but DISARMED — 'continue-on-error' or 'if:' means a red verify no longer stops the release:" >&2
    sed 's/^/    /' "$disabled" >&2
    rc=1
  fi

  # Order: nothing may be built, signed, SBOM'd, attested or published before
  # the gate. JOB-scoped, not file-scoped: release.yaml also carries a
  # pull_request-only `snapshot` job whose goreleaser step legitimately precedes
  # everything (a file-scoped comparison reds on the clean tree — it did).
  local jobstart jobend
  local jobhits="$WORK/hits.release_job"
  grep -n '^  release:$' "$wf" >"$jobhits" || true
  jobstart="$(first_line "$jobhits" | cut -d: -f1)"
  if [[ -z "$jobstart" ]]; then
    echo "  RELSE-05: release.yaml has no '  release:' job — the ordering assertion has no scope" >&2
    return 1
  fi
  jobend="$(awk -v s="$jobstart" 'NR > s && /^  [a-zA-Z0-9_-]+:$/ { print NR; exit }' "$wf")"
  [[ -n "$jobend" ]] || jobend="$(wc -l <"$wf" | tr -d '[:space:]')"
  if ((lineno < jobstart || lineno > jobend)); then
    echo "  RELSE-05: the verify-green gate step (line $lineno) is not inside the release job (lines $jobstart..$jobend) — it gates the wrong job" >&2
    return 1
  fi

  # Marker set is positive-controlled — if none matched, the ordering assertion
  # would pass over any ordering at all.
  local builders="$WORK/hits.release_builders"
  grep -En 'uses:[[:space:]]*(goreleaser/goreleaser-action|sigstore/cosign-installer|anchore/sbom-action|actions/attest|softprops/action-gh-release)' "$wf" |
    awk -F: -v s="$jobstart" -v e="$jobend" '$1 + 0 >= s + 0 && $1 + 0 <= e + 0 { print }' >"$builders" || true
  local n_builders
  n_builders="$(wc -l <"$builders" | tr -d '[:space:]')"
  if ((n_builders < 3)); then
    echo "  RELSE-05: found only $n_builders build/sign/publish action(s) in release.yaml; at least 3 are expected — the ordering assertion would be vacuous" >&2
    return 1
  fi
  local early="$WORK/hits.release_order"
  awk -F: -v gate="$lineno" '$1 + 0 < gate + 0 { print }' "$builders" >"$early" || true
  if [[ -s "$early" ]]; then
    echo "  RELSE-05: build/sign/publish step(s) precede the verify-green gate (gate at line $lineno) — the gate no longer gates:" >&2
    sed 's/^/    /' "$early" >&2
    rc=1
  fi
  return "$rc"
}

