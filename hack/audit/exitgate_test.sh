# Normalises the Appendix-B table to `id|sev|disposition|owner|evidence`.
disposition_rows() { # <spec>
  awk -F'|' '
    /^## Appendix B/ { intable = 1; next }
    intable && /^### / { intable = 0 }
    intable && NF >= 6 {
      id = $2; sev = $3; disp = $4; owner = $5; ev = $6
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", id)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", sev)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", disp)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", owner)
      gsub(/^[[:space:]]+|[[:space:]]+$/, "", ev)
      if (id ~ /^[A-Z]+-[0-9]+$/) printf "%s|%s|%s|%s|%s\n", id, sev, disp, owner, ev
    }
  ' "$1"
}

check_disposition_table() { # <spec> <backlog> <decisions>
  local spec="$1" backlog="$2" decisions="$3" rc=0
  local f
  for f in "$spec" "$backlog" "$decisions"; do
    [[ -f "$f" ]] || {
      echo "  REQ-AUD-S18-02: missing $f" >&2
      return 1
    }
  done

  grep -Fq '## Appendix B' "$spec" || {
    echo "  REQ-AUD-S18-02: the spec has no '## Appendix B' finding->disposition table — every 2026-08-06 finding is now undispositioned" >&2
    return 1
  }

  local rows="$WORK/disposition.rows"
  disposition_rows "$spec" >"$rows"
  local n
  n="$(wc -l <"$rows" | tr -d '[:space:]')"
  if ((n == 0)); then
    echo "  REQ-AUD-S18-02: the Appendix B table parsed to ZERO rows — the extraction broke, so every disposition assertion below would be vacuous" >&2
    return 1
  fi

  # Coverage, both directions.
  local id
  for id in "${AUDIT_FINDINGS[@]}"; do
    local hits
    hits="$(count_prefix_lines "$rows" "$id|")"
    if ((hits == 0)); then
      echo "  $id: no disposition row in the spec's Appendix B table — a 2026-08-06 audit finding with no recorded disposition (REQ-AUD-S18-02)" >&2
      rc=1
    elif ((hits > 1)); then
      echo "  $id: $hits disposition rows in Appendix B; exactly one is required (REQ-AUD-S18-02)" >&2
      rc=1
    fi
  done

  local known="$WORK/disposition.known"
  printf '%s\n' "${AUDIT_FINDINGS[@]}" | sort >"$known"
  local seen="$WORK/disposition.seen"
  cut -d'|' -f1 "$rows" | sort -u >"$seen"
  local extra="$WORK/disposition.extra"
  comm -13 "$known" "$seen" >"$extra" || true
  if [[ -s "$extra" ]]; then
    echo "  REQ-AUD-S18-02: Appendix B carries row(s) for ID(s) that are not 2026-08-06 audit findings — the table and the gate's canonical list disagree, so one of them is wrong:" >&2
    sed 's/^/    /' "$extra" >&2
    rc=1
  fi

  if ((n != AUDIT_FINDINGS_COUNT)); then
    echo "  REQ-AUD-S18-02: Appendix B has $n rows, the audit has $AUDIT_FINDINGS_COUNT findings" >&2
    rc=1
  fi

  # Row-level resolution.
  local line rid rdisp rowner rev
  while IFS='|' read -r rid _ rdisp rowner rev; do
    case "$rdisp" in
    Done)
      if [[ ! "$rowner" =~ ^AUD-S[0-9][0-9]$ ]]; then
        echo "  $rid: disposition Done but owner '$rowner' is not an AUD-Snn story (REQ-AUD-S18-02)" >&2
        rc=1
        continue
      fi
      grep -Fq "## $rowner " "$spec" || {
        echo "  $rid: disposition Done cites story $rowner, but the spec has no '## $rowner' heading — the finding is marked closed against a story that does not exist" >&2
        rc=1
      }
      local reqs
      reqs="$(printf '%s\n' "$rev" | grep -Eo 'REQ-AUD-S[0-9]+-[0-9]+' | sort -u || true)"
      if [[ -z "$reqs" ]]; then
        echo "  $rid: disposition Done but the evidence cell names no REQ-AUD-Snn-nn requirement — 'Done' with no evidence is an assertion, not a disposition" >&2
        rc=1
        continue
      fi
      local req
      while IFS= read -r req; do
        [[ -n "$req" ]] || continue
        grep -Fq "**$req**" "$spec" || {
          echo "  $rid: disposition Done cites $req, which is defined nowhere in the spec — the evidence does not resolve" >&2
          rc=1
        }
        [[ "$req" == "REQ-AUD-${rowner#AUD-}"-* ]] || {
          echo "  $rid: evidence $req does not belong to the cited story $rowner" >&2
          rc=1
        }
      done <<<"$reqs"
      ;;
    Operator)
      if [[ ! "$rowner" =~ ^AUD- ]]; then
        echo "  $rid: disposition Operator but owner '$rowner' is not an AUD-* backlog residual row" >&2
        rc=1
        continue
      fi
      grep -Fq "**$rowner**" "$backlog" || {
        echo "  $rid: disposition Operator cites backlog row $rowner, which does not exist in $backlog — the residual is fenced to nobody" >&2
        rc=1
      }
      ;;
    Accepted)
      if [[ ! "$rowner" =~ ^D-[0-9]+$ ]]; then
        echo "  $rid: disposition Accepted but owner '$rowner' is not a D-nnn decision row — an acceptance that is not written down is a silent decision (AGENTS.md rule 6)" >&2
        rc=1
        continue
      fi
      local drow="$WORK/disposition.drow"
      grep -F "| $rowner |" "$decisions" >"$drow" || true
      if [[ ! -s "$drow" ]]; then
        echo "  $rid: disposition Accepted cites $rowner, which does not exist in $decisions" >&2
        rc=1
        continue
      fi
      grep -Fq -- "$rid" "$drow" || {
        echo "  $rid: decision row $rowner exists but does not mention $rid — the acceptance is not actually logged for this finding" >&2
        rc=1
      }
      ;;
    *)
      echo "  $rid: disposition '$rdisp' is not one of Done / Operator / Accepted (REQ-AUD-S18-02)" >&2
      rc=1
      ;;
    esac
  done <"$rows"
  return "$rc"
}

# The gate must never be readable as "all known fail-opens are closed". OQ-27
# and OQ-28 were found DURING this epic, are not audit findings, and blocked the
# tag independently (OQ-27 has since been closed by D-131; OQ-28 by D-133 plus
# D-129's provider-layer guard -- all three on `main`).
# Tolerant on the NUMBER (four lanes are numbering concurrently) and on the
# STATUS token each row carries — a row that closes must stay in the table as
# the record — strict on presence and on the cited question resolving.
check_post_audit_blockers() { # <spec> <open-questions>
  local spec="$1" oq="$2" rc=0
  [[ -f "$spec" ]] || {
    echo "  AUD-S18: missing $spec" >&2
    return 1
  }
  [[ -f "$oq" ]] || {
    echo "  AUD-S18: missing $oq" >&2
    return 1
  }
  grep -Fq '### Post-audit release blockers' "$spec" || {
    echo "  AUD-S18: the spec has no 'Post-audit release blockers' section — without it a green exit gate reads as release clearance while decision-path fail-opens found after the audit are still open" >&2
    return 1
  }

  local rows="$WORK/blockers.rows"
  awk '
    /^### Post-audit release blockers/ { inblock = 1; next }
    inblock && /^## / { inblock = 0 }
    inblock && /^\| / && !/^\| -/ && !/^\| Defect \|/ { print }
  ' "$spec" >"$rows"
  local n
  n="$(wc -l <"$rows" | tr -d '[:space:]')"
  if ((n < 2)); then
    echo "  AUD-S18: the Post-audit release blockers table has $n row(s); at least 2 are expected (OQ-27 relational CEL compare, OQ-28 repo_file symlink escape — closed rows stay, they are the record) — the section went empty, so the scope disclaimer is decorative" >&2
    return 1
  fi

  local line ids
  while IFS= read -r line; do
    ids="$(printf '%s\n' "$line" | grep -Eo 'OQ-[0-9]+' | sort -u || true)"
    if [[ -z "$ids" ]]; then
      echo "  AUD-S18: a Post-audit release blocker row cites no OQ-<n>, so it resolves to nothing: $line" >&2
      rc=1
      continue
    fi
    # Not `printf … | grep -q`: the early read-end close raises SIGPIPE on the
    # writer and, under `set -o pipefail`, the pipeline reports 141 — a status
    # this branch would read as "no status token", intermittently.
    printf '%s\n' "$line" >"$WORK/blockers.line"
    grep -Eq '(OPEN|CLOSED)' "$WORK/blockers.line" || {
      echo "  AUD-S18: a Post-audit release blocker row carries no OPEN/CLOSED status token: $line" >&2
      rc=1
    }
    local id
    while IFS= read -r id; do
      [[ -n "$id" ]] || continue
      grep -Fq "| $id |" "$oq" || {
        echo "  AUD-S18: post-audit blocker cites $id, which does not exist in $oq — the blocker is named but unresolvable" >&2
        rc=1
      }
    done <<<"$ids"
  done <"$rows"
  return "$rc"
}

# ============================================================================
# CI wiring — this gate runs in release-exitgate, undisarmed, with NO arguments
# ============================================================================

check_ci_wiring() { # <workflows-dir>
  local dir="$1" rc=0
  local wf="$dir/verify.yaml"
  [[ -f "$wf" ]] || {
    echo "  AUD-S18: missing $wf" >&2
    return 1
  }
  local cmds="$WORK/cmd.verify"
  command_view "$wf" >"$cmds"

  # Exact command, no arguments: `--text-only` skips the toolchain layer, so an
  # invocation carrying it would be a disarm.
  local hits="$WORK/hits.audit_wiring"
  grep -E '^[0-9]+:bash[[:space:]]+hack/audit/exitgate_test\.sh[[:space:]]*$' "$cmds" >"$hits" || true
  if [[ ! -s "$hits" ]]; then
    local loose="$WORK/hits.audit_wiring_loose"
    grep -F 'hack/audit/exitgate_test.sh' "$cmds" >"$loose" || true
    if [[ -s "$loose" ]]; then
      echo "  AUD-S18: verify.yaml invokes hack/audit/exitgate_test.sh with arguments — '--text-only' skips the toolchain layer, so an argument-carrying CI invocation is a disarmed gate:" >&2
      sed 's/^/    /' "$loose" >&2
    else
      echo "  AUD-S18: verify.yaml does not RUN 'bash hack/audit/exitgate_test.sh' as an actual command — the audit exit gate would only ever run on the author's machine" >&2
    fi
    return 1
  fi

  local lineno
  lineno="$(awk -F: 'NR == 1 { print $1 }' "$hits")"
  local step="$WORK/step.audit_wiring"
  isolate_step "$wf" "$lineno" '^      - ' >"$step" || true
  local n_step
  n_step="$(wc -l <"$step" | tr -d '[:space:]')"
  if [[ ! -s "$step" ]] || ((n_step > 8)); then
    echo "  AUD-S18: could not isolate the audit exit-gate step in verify.yaml (got $n_step lines, expected 1..8) — the extraction broke, so the disarm assertion would be vacuous" >&2
    return 1
  fi
  grep -Eq '^      - ' "$step" || {
    echo "  AUD-S18: the isolated region does not START with a step marker — it is not a step" >&2
    return 1
  }
  grep -Fq 'hack/audit/exitgate_test.sh' "$step" || {
    echo "  AUD-S18: the isolated step does not contain the gate invocation — the wrong step was isolated" >&2
    return 1
  }
  local n_run
  n_run="$(step_run_count "$step")"
  if ((n_run != 1)); then
    echo "  AUD-S18: the isolated region carries $n_run 'run:' key(s), not 1 — two steps were merged (deleting this step's '- name:' line does exactly that), so the env:/if:/continue-on-error: assertions below would be reading a region that is not one step" >&2
    return 1
  fi
  local disabled="$WORK/hits.audit_wiring_disabled"
  if step_disarmed "$step" "$disabled"; then
    echo "  AUD-S18: the audit exit-gate step is present but DISARMED — 'continue-on-error' or 'if:' means a red exit gate does not fail the job:" >&2
    sed 's/^/    /' "$disabled" >&2
    rc=1
  fi

  # `--text-only` is not the only way to hollow this gate out from the workflow:
  # a step-level `env:` can set ASSENT_AUDIT_SCHEMA_BASE and make check (6)
  # compare the tree against itself. check_schema_freeze refuses a non-tag base
  # on its own, but the step carrying NO env at all is the cheaper invariant and
  # it also covers whatever knob is added next. The gate needs no environment.
  local envkeys="$WORK/hits.audit_wiring_env"
  grep -En '^[[:space:]]*env:' "$step" >"$envkeys" || true
  if [[ -s "$envkeys" ]]; then
    echo "  AUD-S18: the audit exit-gate step carries an 'env:' block — this gate takes no configuration, and an env key (ASSENT_AUDIT_SCHEMA_BASE above all) is a way to hollow out a check while the step still looks wired:" >&2
    sed 's/^/    /' "$envkeys" >&2
    rc=1
  fi

  # The step-level `env:` ban above is necessary but not sufficient: a JOB-level
  # or WORKFLOW-level `env:`, or an earlier step writing `>> $GITHUB_ENV`, sets
  # the same variable without ever touching this step. One absence assertion over
  # the whole workflow directory closes all three at once. check_schema_freeze's
  # vX.Y.Z-tag constraint is the primary defence; this is the one that also
  # refuses a base that IS a tag but is not the frozen baseline.
  local wfiles="$WORK/wiring.workflows"
  find "$dir" -type f \( -name '*.yaml' -o -name '*.yml' \) >"$wfiles"
  local n_wf
  n_wf="$(wc -l <"$wfiles" | tr -d '[:space:]')"
  if ((n_wf < 3)); then
    echo "  AUD-S18: found only $n_wf workflow file(s) under $dir; at least 3 are expected — the inventory broke, so the baseline-override sweep below would be vacuous" >&2
    return 1
  fi
  local override="$WORK/hits.audit_wiring_base"
  : >"$override"
  local wfile
  while IFS= read -r wfile; do
    [[ -n "$wfile" ]] || continue
    grep -Fn -- 'ASSENT_AUDIT_SCHEMA_BASE' "$wfile" | sed "s|^|$wfile:|" >>"$override" || true
  done <"$wfiles"
  if [[ -s "$override" ]]; then
    echo "  AUD-S18: ASSENT_AUDIT_SCHEMA_BASE is set somewhere under $dir — the schema-freeze baseline must never be steered from CI (a job-level env, a workflow-level env or a '>> \$GITHUB_ENV' write disarms check (6) without touching the gate step at all, D-132):" >&2
    sed 's/^/    /' "$override" >&2
    rc=1
  fi

  # It must live in release-exitgate: the verify job runs on pull_request, where
  # `task check`'s changelog stage is red by construction (D-125).
  local joblines="$WORK/hits.audit_wiring_job"
  grep -n '^  release-exitgate:' "$wf" >"$joblines" || true
  local jobline
  jobline="$(first_line "$joblines" | cut -d: -f1)"
  if [[ -z "$jobline" ]]; then
    echo "  AUD-S18: verify.yaml has no release-exitgate job — REQ-AUD-S18-01 requires the gate to be wired there" >&2
    return 1
  fi
  if ((lineno < jobline)); then
    echo "  AUD-S18: the audit exit-gate step sits at line $lineno, before the release-exitgate job at line $jobline — it is wired into the wrong job (the verify job runs on pull_request, where D-125 makes the changelog stage red by construction)" >&2
    rc=1
  fi

  # A JOB-level `continue-on-error: true` makes every step in release-exitgate
  # advisory — the gate runs, reds, and the workflow still concludes success.
  # Job-scoped, at the job's own indent, so a step-level key (already covered
  # above, and legitimate on no step of this job) is not double-counted.
  local jobend
  jobend="$(awk -v s="$jobline" 'NR > s && /^  [a-zA-Z0-9_-]+:$/ { print NR; exit }' "$wf")"
  [[ -n "$jobend" ]] || jobend="$(wc -l <"$wf" | tr -d '[:space:]')"
  local jobcoe="$WORK/hits.audit_wiring_jobcoe"
  awk -v s="$jobline" -v e="$jobend" 'NR >= s && NR <= e && /^    continue-on-error:/ { printf "%d:%s\n", NR, $0 }' "$wf" >"$jobcoe"
  if [[ -s "$jobcoe" ]]; then
    echo "  AUD-S18: the release-exitgate JOB carries a job-level 'continue-on-error:' — every step in it, this gate included, becomes advisory and a red exit gate no longer fails the workflow:" >&2
    sed 's/^/    /' "$jobcoe" >&2
    rc=1
  fi

  # The job's `if:` is the other job-level disarm, and the one this gate first
  # shipped unguarded. `if: false` skips release-exitgate entirely; the job then
  # reports SUCCESS (a skipped job is not a failed one), so every step above —
  # this gate included — silently stops running while the workflow stays green.
  #
  # The gate does NOT pin the expression. `github.event_name != 'pull_request'`
  # is load-bearing (D-125: on pull_request the changelog stage is red by
  # construction) but it is not the only legitimate spelling, and requiring the
  # `if:` to be PRESENT would pin one wording forever. Deleting it is also
  # self-announcing: release-exitgate would then run on pull_request and red
  # there for the changelog stage.
  #
  # What IS refused is a CONSTANT: a job-level `if:` whose value is the literal
  # `true` or `false`. That is trivial to state and impossible to argue with —
  # a constant `if:` expresses no condition, so it is either a no-op or a
  # disarm, and both are tells. Normalised before comparing so the refusal is
  # not reworded around: `${{ }}` unwrapped, quotes stripped, comment tail
  # dropped, trimmed, lowercased. `if: false`, `if: ${{ false }}`, `if: 'false'`
  # and `if: true` are therefore all refused; `github.event_name != '…'`
  # normalises to something that is neither literal and passes.
  #
  # SCOPE, stated so this does not become the next overstatement: this closes
  # the CONSTANT case only. A semantically-never-true EXPRESSION — the
  # reviewer's `if: github.event_name == 'deployment_status'` is the worked
  # example — is NOT caught here and cannot be, without evaluating GitHub's
  # expression language against a model of which events reach this workflow.
  # That residual is real, is unchanged by this check, and stays fenced to
  # RELSE-08 (`AUD-RELSE-08` in openspec/specs/backlog.md).
  #
  # Vacuity: the job region (jobline..jobend) is the same region the
  # continue-on-error scan above reads, and both of this check's mutation
  # controls inject their key immediately after `  release-exitgate:` — so a
  # region extraction that collapsed would red those controls, not pass them.
  local jobif="$WORK/hits.audit_wiring_jobif"
  awk -v s="$jobline" -v e="$jobend" '
    BEGIN { Q = sprintf("%c", 39) }
    NR >= s && NR <= e && /^    if:/ {
      v = $0
      sub(/^[[:space:]]*if:[[:space:]]*/, "", v)
      sub(/[[:space:]]+#.*$/, "", v)
      sub(/[[:space:]]+$/, "", v)
      if (v ~ /^\$\{\{.*\}\}$/) {
        sub(/^\$\{\{[[:space:]]*/, "", v)
        sub(/[[:space:]]*\}\}$/, "", v)
      }
      gsub(/"/, "", v)
      gsub(Q, "", v)
      sub(/^[[:space:]]+/, "", v)
      sub(/[[:space:]]+$/, "", v)
      if (tolower(v) == "true" || tolower(v) == "false") printf "%d:%s\n", NR, $0
    }
  ' "$wf" >"$jobif"
  if [[ -s "$jobif" ]]; then
    echo "  AUD-S18: the release-exitgate JOB carries a CONSTANT job-level 'if:' — a literal true/false expresses no condition, so the job is either unconditionally skipped (a skipped job reports SUCCESS, and this gate never runs while the workflow stays green) or unconditionally run; either way the condition has been disarmed rather than changed:" >&2
    sed 's/^/    /' "$jobif" >&2
    rc=1
  fi
  return "$rc"
}

