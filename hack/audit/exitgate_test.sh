# The Taskfile's `check:` list must be exactly the pinned stages. Without
# this, deleting `- task: changelog-verify` reopens RELSE-01 with `task check`
# still exiting 0 — the regression the whole story exists to prevent.
check_check_wiring() { # <taskfile>
  local tf="$1" rc=0
  [[ -f "$tf" ]] || {
    echo "  RELSE-01: missing $tf" >&2
    return 1
  }

  # Isolate `check:`'s cmds block: from the `  check:` key to the next
  # same-indent task key. Comment-stripped, so a commented-out stage does not
  # count as wired (review finding F1).
  local block="$WORK/taskfile.check"
  awk '
    /^  check:$/ { inblock = 1; next }
    inblock && /^  [a-zA-Z0-9_:-]+:$/ { inblock = 0 }
    inblock {
      s = $0
      sub(/^[[:space:]]+/, "", s)
      if (substr(s, 1, 1) == "#") next
      print s
    }
  ' "$tf" >"$block"

  local stages="$WORK/taskfile.check.stages"
  grep -E '^- task: [a-zA-Z0-9_:-]+$' "$block" >"$stages" || true
  local n
  n="$(wc -l <"$stages" | tr -d '[:space:]')"
  if ((n == 0)); then
    echo "  RELSE-01: found NO '- task:' entries in the Taskfile check: block — the extraction broke, so every stage assertion below would be vacuous" >&2
    return 1
  fi

  local want
  for want in "${CHECK_STAGES[@]}"; do
    has_prefix_line "$stages" "- task: $want" || {
      if [[ "$want" == "changelog-verify" ]]; then
        echo "  RELSE-01: 'task check' no longer runs changelog-verify — the CHANGELOG drift gate is wired nowhere again (this is the finding that already regressed once, post-tag)" >&2
      else
        echo "  AUD-S18: 'task check' no longer runs the pinned stage '$want' — the exit gate grades all ${#CHECK_STAGES[@]} stages, and task check aborts at the first failure, so a dropped stage is invisible in the exit code" >&2
      fi
      rc=1
    }
  done

  if ((n != ${#CHECK_STAGES[@]})); then
    echo "  AUD-S18: Taskfile check: lists $n stages, the gate pins ${#CHECK_STAGES[@]} — an unpinned stage is a stage this gate does not grade; add it to CHECK_STAGES deliberately" >&2
    sed 's/^/    /' "$stages" >&2
    rc=1
  fi
  return "$rc"
}

# Every pinned stage must have actually RUN. go-task prints `task: [<name>] <cmd>`
# per stage; that transcript is the only evidence a stage executed, because
# `task check` aborts at the first failure and the exit code cannot distinguish
# "all stages green" from "stage list truncated to 2".
check_check_stages() { # <transcript>
  local tr="$1" rc=0
